#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const crypto = require('node:crypto');

function readResults(file) {
  if (!file || !fs.existsSync(file)) {
    throw new Error(`Jest result file is missing: ${file || '(unset)'}`);
  }
  const raw = fs.readFileSync(file);
  const results = JSON.parse(raw.toString('utf8'));
  const metadataPath = `${file}.meta.json`;
  if (!fs.existsSync(metadataPath)) throw new Error(`Jest result metadata is missing: ${metadataPath}`);
  const metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'));
  const hash = crypto.createHash('sha256').update(raw).digest('hex');
  if (metadata.resultSha256 !== hash) throw new Error(`Jest result is stale or does not match its metadata: ${file}`);
  if (metadata.wasInterrupted || results.wasInterrupted) throw new Error(`Jest run was interrupted: ${file}`);
  if (!Number.isFinite(results.numTotalTestSuites) || results.numTotalTestSuites !== (results.testResults || []).length) {
    throw new Error(`Jest result is incomplete: ${file}`);
  }
  if (metadata.suiteCount !== results.numTotalTestSuites || metadata.startedAt !== results.startTime
      || metadata.finishedAt < metadata.startedAt) {
    throw new Error(`Jest result metadata is incomplete or stale: ${file}`);
  }
  const stat = fs.statSync(file);
  if (stat.mtimeMs < metadata.startedAt) throw new Error(`Jest result predates its recorded run: ${file}`);
  return { results, metadata };
}

function normalizePath(file) {
  const marker = '/api/';
  const index = file.lastIndexOf(marker);
  return index >= 0 ? file.slice(index + marker.length) : file;
}

function normalizeTitle(title) {
  return title.replace(/(?:\/[^/\s]+)*\/(?:\.baseline\/)?api\//g, 'api/');
}

function failingCases(results) {
  const failures = new Set();
  for (const suite of results.testResults || []) {
    const file = normalizePath(suite.testFilePath || suite.name || 'unknown-suite');
    const failed = (suite.assertionResults || []).filter(test => test.status === 'failed');
    for (const test of failed) {
      const title = normalizeTitle(
        [...(test.ancestorTitles || []), test.title].filter(Boolean).join(' › ')
      );
      failures.add(`${file} :: ${title || '(unnamed failing test)'}`);
    }
    if (suite.status === 'failed' && failed.length === 0) {
      failures.add(`${file} :: (suite-level failure)`);
    }
  }
  return failures;
}

try {
  const { results: baseline, metadata: baseMeta } = readResults(process.argv[2]);
  const { results: pullRequest, metadata: prMeta } = readResults(process.argv[3]);
  const expectedRunId = process.env.API_JEST_EXPECTED_RUN_ID;
  const expectedBaseCommit = process.env.API_JEST_EXPECTED_BASE_COMMIT;
  const expectedPrCommit = process.env.API_JEST_EXPECTED_PR_COMMIT;
  if (!expectedRunId || !expectedBaseCommit || !expectedPrCommit) {
    throw new Error('Expected run ID, preparation commit, and PR head commit are required.');
  }
  if (baseMeta.runId !== expectedRunId || prMeta.runId !== expectedRunId) {
    throw new Error('Jest results were generated by a different workflow run.');
  }
  if (baseMeta.sourceCommit !== expectedBaseCommit || baseMeta.baseCommit !== expectedBaseCommit
      || prMeta.sourceCommit !== expectedPrCommit || prMeta.baseCommit !== expectedBaseCommit) {
    throw new Error('Jest results were generated from unexpected commits.');
  }
  if (baseMeta.nodeVersion !== prMeta.nodeVersion || baseMeta.npmVersion !== prMeta.npmVersion
      || baseMeta.nodeVersion !== 'v22.23.4' || baseMeta.npmVersion !== '11.19.1'
      || baseMeta.lockfileSha256 !== prMeta.lockfileSha256
      || baseMeta.testCommand !== prMeta.testCommand) {
    throw new Error('Baseline and PR test environments do not match the required runtime, lockfile, or command.');
  }
  const baselineFailures = failingCases(baseline);
  const prFailures = failingCases(pullRequest);
  const newFailures = [...prFailures].filter(name => !baselineFailures.has(name)).sort();
  const resolvedFailures = [...baselineFailures].filter(name => !prFailures.has(name)).sort();
  const summary = [
    '## API baseline comparison',
    `- Preparation baseline: ${baseline.numFailedTests || 0} failed tests across ${baseline.numFailedTestSuites || 0} failed suites.`,
    `- Pull request: ${pullRequest.numFailedTests || 0} failed tests across ${pullRequest.numFailedTestSuites || 0} failed suites.`,
    `- PR-only failing tests: ${newFailures.length}.`,
    `- Baseline failures resolved by the PR: ${resolvedFailures.length}.`,
    ...(resolvedFailures.length ? resolvedFailures.map(name => `  - ${name}`) : []),
    ...(newFailures.length ? newFailures.map(name => `  - ${name}`) : ['- No new failing tests compared with the unchanged preparation base.']),
  ].join('\n');
  console.log(summary);
  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${summary}\n`);
  }
  if (newFailures.length) process.exitCode = 1;
} catch (error) {
  console.error(`API baseline comparison failed: ${error.message}`);
  process.exitCode = 1;
}
